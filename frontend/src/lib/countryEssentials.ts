export function getCountryEssentials(country: string | undefined): CountryEssentials | null {
  if (!country) return null;
  const trimmed = country.trim();
  if (ESSENTIALS[trimmed]) return ESSENTIALS[trimmed];
  // Подстраховка: ищем по подстроке (на случай вариаций «ОАЭ — Дубай»).
  const lower = trimmed.toLowerCase();
  for (const [name, data] of Object.entries(ESSENTIALS)) {
    if (name.toLowerCase() === lower) return data;
    if (lower.includes(name.toLowerCase()) || name.toLowerCase().includes(lower)) {
      return data;
    }
  }
  return null;
}
